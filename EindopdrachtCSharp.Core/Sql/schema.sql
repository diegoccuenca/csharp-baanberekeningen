-- Tabellen voor de C# eindopdracht (SQLite).
CREATE TABLE IF NOT EXISTS Personen (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Naam TEXT NOT NULL CHECK (length(trim(Naam)) > 0),
    Leeftijd INTEGER NOT NULL CHECK (Leeftijd BETWEEN 0 AND 120)
);

CREATE TABLE IF NOT EXISTS Opleidingen (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Naam TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS Beroepen (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Naam TEXT NOT NULL
);
